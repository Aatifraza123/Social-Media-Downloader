const { exec } = require('child_process');
const { promisify } = require('util');
const fs = require('fs').promises;
const path = require('path');
const logger = require('../utils/logger');
const execAsync = promisify(exec);

class SubtitleService {
  constructor() {
    this.storagePath = path.resolve(process.env.STORAGE_PATH || './storage/downloads');
  }

  /**
   * Get available subtitles for a video URL
   */
  async getAvailableSubtitles(url) {
    const ytdlpPath = process.env.YT_DLP_PATH || 'yt-dlp';
    
    try {
      const { stdout } = await execAsync(
        `"${ytdlpPath}" --list-subs --skip-download "${url}"`,
        { timeout: 15000 }
      );

      // Parse subtitle list from output
      const subtitles = this.parseSubtitleList(stdout);
      return subtitles;
    } catch (err) {
      logger.error('Failed to list subtitles:', err.message);
      throw new Error('Could not fetch available subtitles');
    }
  }

  /**
   * Download subtitle in specified language and format
   */
  async downloadSubtitle(url, language = 'en', format = 'srt') {
    const ytdlpPath = process.env.YT_DLP_PATH || 'yt-dlp';
    const fileName = `subtitle_${Date.now()}.${format}`;
    const outputPath = path.join(this.storagePath, fileName);

    try {
      const command = `"${ytdlpPath}" --write-sub --sub-lang ${language} --sub-format ${format} --skip-download -o "${outputPath}" "${url}"`;
      logger.info(`Downloading subtitle: ${command}`);

      await execAsync(command, { timeout: 60000 });

      // yt-dlp adds language code to filename, find the actual file
      const actualFile = `${outputPath}.${language}.${format}`;
      
      try {
        await fs.access(actualFile);
        return {
          success: true,
          fileName: path.basename(actualFile),
          filePath: actualFile,
          language,
          format
        };
      } catch {
        // If subtitle file doesn't exist, check for auto-generated
        const autoFile = `${outputPath}.${language}-auto.${format}`;
        try {
          await fs.access(autoFile);
          return {
            success: true,
            fileName: path.basename(autoFile),
            filePath: autoFile,
            language,
            format,
            autoGenerated: true
          };
        } catch {
          throw new Error('Subtitle file not found after download');
        }
      }
    } catch (err) {
      logger.error('Subtitle download error:', err.message);
      throw new Error(`Subtitle download failed: ${err.message}`);
    }
  }

  /**
   * Download all available subtitles
   */
  async downloadAllSubtitles(url, format = 'srt') {
    const ytdlpPath = process.env.YT_DLP_PATH || 'yt-dlp';
    const fileName = `subtitle_${Date.now()}`;
    const outputPath = path.join(this.storagePath, fileName);

    try {
      const command = `"${ytdlpPath}" --write-sub --all-subs --sub-format ${format} --skip-download -o "${outputPath}" "${url}"`;
      logger.info(`Downloading all subtitles: ${command}`);

      await execAsync(command, { timeout: 120000 });

      // List all downloaded subtitle files
      const files = await fs.readdir(this.storagePath);
      const subtitleFiles = files.filter(f => f.startsWith(path.basename(fileName)) && f.endsWith(`.${format}`));

      return {
        success: true,
        files: subtitleFiles,
        count: subtitleFiles.length,
        format
      };
    } catch (err) {
      logger.error('All subtitles download error:', err.message);
      throw new Error(`Failed to download subtitles: ${err.message}`);
    }
  }

  /**
   * Parse subtitle list from yt-dlp output
   */
  parseSubtitleList(output) {
    const subtitles = [];
    const lines = output.split('\n');
    let inSubSection = false;

    for (const line of lines) {
      if (line.includes('Available subtitles')) {
        inSubSection = true;
        continue;
      }

      if (inSubSection && line.trim()) {
        // Parse line format: "en  English"
        const match = line.trim().match(/^(\w+)\s+(.+?)(?:\s+\(auto-generated\))?$/);
        if (match) {
          subtitles.push({
            code: match[1],
            language: match[2],
            autoGenerated: line.includes('auto-generated')
          });
        }
      }

      // Stop when we hit automatic captions section or empty lines
      if (line.includes('automatic captions') || (inSubSection && !line.trim())) {
        break;
      }
    }

    return subtitles;
  }

  /**
   * Get subtitle file for download
   */
  async getSubtitleFile(filePath) {
    try {
      await fs.access(filePath);
      return filePath;
    } catch {
      throw new Error('Subtitle file not found');
    }
  }

  /**
   * Delete subtitle file
   */
  async deleteSubtitle(filePath) {
    try {
      await fs.unlink(filePath);
      return { success: true };
    } catch (err) {
      logger.error('Failed to delete subtitle:', err.message);
      throw new Error('Could not delete subtitle file');
    }
  }
}

module.exports = new SubtitleService();
